test('Escape closes the focused inspector and returns focus to its expanded-state toggle', () => {
  const { store } = renderStudio()
  const toggle = screen.getByRole('button', { name: 'Scene' })
  const inspector = screen.getByRole('complementary', { name: 'Scene inspector' })
  const select = screen.getByRole('combobox', { name: 'Selected tool' })
  fireEvent.change(select, { target: { value: 'light' } })
  select.focus()

  fireEvent.keyDown(select, { key: 'Escape' })

  expect(toggle.getAttribute('aria-expanded')).toBe('false')
  expect(toggle.getAttribute('aria-controls')).toBe(inspector.id)
  expect(inspector.hidden).toBe(true)
  expect(document.activeElement).toBe(toggle)
  expect(screen.queryByRole('combobox', { name: 'Selected tool' })).toBeNull()

  fireEvent.click(toggle)
  expect(inspector.hidden).toBe(false)
  expect(toggle.getAttribute('aria-expanded')).toBe('true')
  expect(store.getState().preview.tool).toBe('light')

  const close = screen.getByRole('button', { name: 'Close scene inspector' })
  close.focus()
  fireEvent.click(close)
  expect(document.activeElement).toBe(toggle)
})

