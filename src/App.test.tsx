test('compact panels start closed, open one at a time and preserve focus across a breakpoint', () => {
  viewport.matches = true
  renderStudio()
  const scene = screen.getByRole('button', { name: 'Scene' })
  const pixels = screen.getByRole('button', { name: 'Pixels' })

  expect(screen.queryByRole('complementary')).toBeNull()
  fireEvent.click(scene)
  expect(screen.getByRole('complementary', { name: 'Scene inspector' })).toBeTruthy()
  fireEvent.click(pixels)
  expect(screen.queryByRole('complementary', { name: 'Scene inspector' })).toBeNull()
  expect(screen.getByRole('complementary', { name: 'Pixel inspector' })).toBeTruthy()
  fireEvent.click(pixels)
  expect(screen.queryByRole('complementary')).toBeNull()

  act(() => {
    viewport.matches = false
    viewport.dispatchEvent(new Event('change'))
  })
  expect(screen.getAllByRole('complementary')).toHaveLength(2)
  screen.getByRole('combobox', { name: 'Selected tool' }).focus()
  act(() => {
    viewport.matches = true
    viewport.dispatchEvent(new Event('change'))
  })
  expect(screen.queryByRole('complementary')).toBeNull()
  expect(document.activeElement).toBe(scene)
})

